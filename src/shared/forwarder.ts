// Email alias forwarders, called the way Bitwarden's generator calls them. The API key is kept per
// account, encrypted with the account key (see generator-history.ts), and never sent back to the popup.
export const FORWARDERS = {
  simplelogin: { origin: "https://app.simplelogin.io/*" },
  addy: { origin: "https://app.addy.io/*" },
} as const;
export type Forwarder = keyof typeof FORWARDERS;

export function isForwarder(value: unknown): value is Forwarder {
  return value === "simplelogin" || value === "addy";
}

// Creates a new alias and returns its address. website: the host it is for, used as its note.
export async function createAlias(
  service: Forwarder,
  apiKey: string,
  options: { domain: string; website?: string | undefined },
  fetchImpl: typeof fetch = fetch,
): Promise<string> {
  const note = options.website ? `Website: ${options.website}. Generated by Firnkey.` : "Generated by Firnkey.";
  const init = { method: "POST", credentials: "omit", referrerPolicy: "no-referrer", signal: AbortSignal.timeout(15_000) } as const;
  const response = service === "simplelogin"
    ? await fetchImpl(`https://app.simplelogin.io/api/alias/random/new${options.website ? `?hostname=${encodeURIComponent(options.website)}` : ""}`, {
      ...init,
      headers: { Authentication: apiKey, "Content-Type": "application/json" },
      body: JSON.stringify({ note }),
    })
    : await fetchImpl("https://app.addy.io/api/v1/aliases", {
      ...init,
      headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json", "X-Requested-With": "XMLHttpRequest" },
      body: JSON.stringify({ domain: options.domain, description: note }),
    });
  const name = service === "simplelogin" ? "SimpleLogin" : "addy.io";
  if (response.status === 401 || response.status === 403) throw new Error(`${name} did not accept the API key.`);
  if (!response.ok) throw new Error(`${name} could not create an alias (HTTP ${response.status}).`);
  const body = (await response.json().catch(() => undefined)) as { alias?: unknown; data?: { email?: unknown } } | undefined;
  const alias = service === "simplelogin" ? body?.alias : body?.data?.email;
  if (typeof alias !== "string" || !/^[^\s@]+@[^\s@]+$/.test(alias) || alias.length > 320) {
    throw new Error(`${name} sent an unexpected answer.`);
  }
  return alias;
}
